/** Глиф VKUI 24×24 масштабируем и центрируем в кружке метки (10, 10). */
function glyphMarkup(shape: GlyphShape): string {
  const paths = shape.paths.map((path) => `<path d="${path}" fill="#fff"/>`).join('')
  return `<g transform="translate(2.8 2.8) scale(0.6)" fill-rule="evenodd" clip-rule="evenodd">${paths}</g>`
}

/** SVG-метка площадки: белая капля, цветной кружок и белый глиф. */
function pinSvg(category: ViewerLocationCategory): string {
  const glyph = PLACEMARK_GLYPH_BY_CATEGORY[category]
  const color = PLACEMARK_GLYPH_COLOR[glyph]
  // Поля 2 px вокруг капли — под тень: кончик хвоста остаётся в (12, 25).
  return [
    '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="27" viewBox="-2 -2 24 27">',
    '<filter id="s" x="-50%" y="-50%" width="200%" height="200%">',
    '<feDropShadow dx="0" dy="2" stdDeviation="1" flood-color="#000" flood-opacity="0.2"/>',
    '</filter>',
    `<g filter="url(#s)"><path d="${PIN_BODY}" fill="#fff"/>`,
    `<circle cx="9.9984" cy="10.004" r="8.1995" fill="${color}"/>`,
    glyphMarkup(GLYPHS[glyph]),
    '</g></svg>',
  ].join('')
}

/** Метка для `iconImageHref`: Yandex Maps принимает SVG как data URI. */
export function placemarkPinHref(category: ViewerLocationCategory): string {
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(pinSvg(category))}`
}
